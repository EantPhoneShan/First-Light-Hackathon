// Turns ChatGPT PNGs in art/raw/ into game-ready WebP in public/assets/, and updates the manifest
// so the game uses them instead of the built-in SVGs.
//
//   npm run art
//
// Name each PNG after its target, e.g. art/raw/part-bus-6u.png, rocket-small.png, role-planner.png,
// scene-title.png. The full list of names and prompts is in art/README.md.
import { readdir, mkdir, writeFile } from 'node:fs/promises'
import { join, parse } from 'node:path'
import sharp from 'sharp'

const RAW = 'art/raw'
const OUT = 'public/assets'
const MANIFEST = 'src/content/artManifest.ts'

/** Target size per kind, from the brief: parts/avatars 256 px, rockets 512 px tall, scenes 1024 px wide. */
function sizeFor(name) {
  if (name.startsWith('rocket-')) return { height: 512 }
  if (name.startsWith('scene-title')) return { width: 1024 }
  if (name.startsWith('event-')) return { width: 512 }
  return { width: 256, height: 256 }
}

await mkdir(OUT, { recursive: true })
const files = (await readdir(RAW).catch(() => [])).filter((f) => /\.(png|jpe?g|webp)$/i.test(f))
const done = []

for (const file of files) {
  const name = parse(file).name
  const { width, height } = sizeFor(name)
  await sharp(join(RAW, file))
    .trim({ threshold: 10 }) // crop empty transparent edges so every image fills its box the same way
    .resize({ width, height, fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .webp({ quality: 85, alphaQuality: 90 })
    .toFile(join(OUT, `${name}.webp`))
  done.push(name)
  console.log(`✓ ${name}.webp`)
}

// Keep anything already processed, so the manifest lists every WebP in public/assets.
const existing = (await readdir(OUT)).filter((f) => f.endsWith('.webp')).map((f) => parse(f).name)
const all = [...new Set([...existing, ...done])].sort()
await writeFile(
  MANIFEST,
  `// Generated by scripts/process-art.mjs. Lists the WebP art in public/assets/.\n// Empty until ChatGPT images are processed; the game then uses the built-in SVGs.\nexport const webpArt = new Set<string>(${JSON.stringify(all, null, 2)})\n`,
)
console.log(files.length ? `Processed ${done.length} image(s). Manifest lists ${all.length}.` : `No images in ${RAW}/ yet. See art/README.md.`)
